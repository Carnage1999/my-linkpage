export type ManageKey = keyof typeof manageCopy.en

export function isManageLanguage(value: string): value is ManageLanguage {
  return MANAGE_LANGUAGES.some((language) => language.code === value)
}

export function manageText(language: string, key: ManageKey, vars?: Record<string, string | number>): string {
  const pack = isManageLanguage(language) ? manageCopy[language] : manageCopy.en
  const template = pack[key] ?? manageCopy.en[key]
  if (!vars) return template
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(vars[name] ?? ''))
}
